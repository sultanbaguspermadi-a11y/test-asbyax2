#!/usr/bin/env node
/**
 * Builds lexicon files from a Wiktextract / kaikki.org JSONL dump of Arabic (language code "ar").
 *
 *   node scripts/build-lexicon.mjs --kaikki data-raw/kaikki.org-dictionary-Arabic.jsonl [--out public/data/lexicon]
 *
 * Outputs (and registers them in <out>/meta.json, replacing earlier output of this script):
 *   wiktionary-ar-lemmas.txt   tier "core"      headwords of lemma entries            -> used by Strict and Expanded
 *   wiktionary-ar-forms.txt    tier "extended"  inflected forms listed by Wiktionary  -> used by Expanded only
 *
 * Filters: single words of Arabic letters only (diacritics/tatweel stripped, 2-15 letters), no proper names,
 * affixes, phrases, symbols; entries whose every sense is tagged misspelling/nonstandard are skipped.
 * The raw dump is NOT part of the repository (see .gitignore / docs/DICTIONARY.md). Wiktionary content is
 * CC BY-SA (and GFDL): the generated files carry an attribution header and must keep it.
 */
import { createReadStream, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createInterface } from 'node:readline'
import { join } from 'node:path'
import { orthographic, isArabicWord } from '../public/js/arabic/normalize.js'

const args = Object.fromEntries(process.argv.slice(2).reduce((a, v, i, all) => (v.startsWith('--') ? [...a, [v.slice(2), all[i + 1]]] : a), []))
if (!args.kaikki) { console.error('usage: node scripts/build-lexicon.mjs --kaikki <file.jsonl> [--out public/data/lexicon]'); process.exit(2) }
const OUT = args.out || 'public/data/lexicon'
const SKIP_POS = new Set(['name', 'proper noun', 'character', 'symbol', 'phrase', 'proverb', 'prefix', 'suffix', 'infix', 'circumfix', 'affix', 'interfix', 'punct', 'abbrev', 'contraction', 'romanization', 'letter', 'num'])
const BAD_SENSE_TAGS = new Set(['misspelling', 'nonstandard'])
const SKIP_FORM_TAGS = new Set(['romanization', 'table-tags', 'inflection-template', 'class', 'multiword-construction'])
const flagFor = pos => (pos === 'verb' ? 'V' : pos === 'noun' || pos === 'adj' || pos === 'adv' ? 'N' : pos === 'prep' ? 'S' : 'X')

const lemmas = new Map(), forms = new Map()
const add = (map, raw, flag) => {
  const w = orthographic(raw)
  if (!isArabicWord(w) || w.length < 2 || w.length > 15) return
  const s = map.get(w) || new Set(); s.add(flag); map.set(w, s)
}
let lines = 0, used = 0
for await (const line of createInterface({ input: createReadStream(args.kaikki, 'utf8'), crlfDelay: Infinity })) {
  if (!line.trim()) continue
  let e; try { e = JSON.parse(line) } catch { continue }
  lines++
  if (e.lang_code && e.lang_code !== 'ar') continue
  if (SKIP_POS.has(e.pos)) continue
  const senses = e.senses || []
  if (senses.length && senses.every(s => (s.tags || []).some(t => BAD_SENSE_TAGS.has(t)))) continue
  const flag = flagFor(e.pos), isForm = senses.length > 0 && senses.every(s => s.form_of || s.alt_of)
  used++
  if (isForm) add(forms, e.word, flag); else add(lemmas, e.word, flag)
  for (const f of e.forms || []) if (!(f.tags || []).some(t => SKIP_FORM_TAGS.has(t))) add(forms, f.form, flag)
}
// a word that is a lemma does not need repeating in the forms tier
for (const w of lemmas.keys()) forms.delete(w)

const header = (title, n) => `# ${title}\n# Source: Wiktionary (Arabic entries) via Wiktextract / kaikki.org. Content licensed CC BY-SA and GFDL - attribution required, see docs/DICTIONARY.md\n# Generated by scripts/build-lexicon.mjs from ${args.kaikki.split(/[\\/]/).pop()} on ${new Date().toISOString().slice(0, 10)}; ${n} entries\n`
const body = m => [...m.entries()].sort(([a], [b]) => a.localeCompare(b, 'ar')).map(([w, f]) => `${w}\t${[...f].sort().join('')}`).join('\n') + '\n'
mkdirSync(OUT, { recursive: true })
const files = [['wiktionary-ar-lemmas.txt', 'core', lemmas, 'Wiktionary Arabic lemmas'], ['wiktionary-ar-forms.txt', 'extended', forms, 'Wiktionary Arabic inflected forms']]
for (const [name, , m, title] of files) writeFileSync(join(OUT, name), header(title, m.size) + body(m))

const metaPath = join(OUT, 'meta.json')
const meta = existsSync(metaPath) ? JSON.parse(readFileSync(metaPath, 'utf8')) : { name: 'Arabic Scrabble lexicon', files: [] }
meta.files = meta.files.filter(f => !f.id.startsWith('wiktionary-ar'))
for (const [name, tier, , ] of files) meta.files.push({ id: name.replace('.txt', ''), tier, path: name, license: 'CC BY-SA 4.0 / GFDL (Wiktionary)', source: 'Wiktionary via Wiktextract (kaikki.org)' })
meta.version = `wiktionary-${new Date().toISOString().slice(0, 10)}+${meta.files.filter(f => !f.id.startsWith('wiktionary')).map(f => f.id).join('+') || 'none'}`
meta.note = 'Lexicon built from Wiktionary data; see docs/DICTIONARY.md for coverage and limitations.'
writeFileSync(metaPath, JSON.stringify(meta, null, 2) + '\n')
console.log(`read ${lines} entries, used ${used}; lemmas: ${lemmas.size}, extra forms: ${forms.size}; wrote ${OUT}/`)
